// Assembles build/runtime (what electron-builder ships as `resources/runtime`) from
// the repository builds:
//   backend/          penpot.jar, log4j2.xml, builtin-templates/  (from --backend, the
//                     backend bundle: `./manage.sh build-backend-bundle` or backend/target/dist)
//   frontend/         built frontend (from --frontend: `./manage.sh build-frontend-bundle`
//                     or frontend/target/dist)
//   mcp-plugin/       MCP plugin (frontend's plugins/mcp, else mcp/packages/plugin/dist)
//   daemon/           mcp/packages/server build + production node_modules (pnpm deploy)
//   media-processor/  media-processor build + production node_modules
//   version.json      versions and commit of the bundled parts
//   licenses/         license texts of the bundled parts
// jre/ and postgres/ come from scripts/fetch-runtime.mjs.
//
// Usage: node scripts/stage.mjs [--backend <dir>] [--frontend <dir>] [--skip-node-builds]
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(ROOT, "..");
const RUNTIME = join(ROOT, "build", "runtime");
const INPUTS = join(ROOT, "build", "inputs");
const WIN = process.platform === "win32";

function arg(name, fallback) {
    const i = process.argv.indexOf(name);
    return i >= 0 ? resolve(process.argv[i + 1]) : fallback;
}

function run(command, args, cwd) {
    console.log(`> ${command} ${args.join(" ")}  (${cwd})`);
    const result = spawnSync(command, args, { cwd, stdio: "inherit", shell: WIN });
    if (result.status !== 0) {
        throw new Error(`${command} ${args.join(" ")} failed in ${cwd}`);
    }
}

function pnpm(args, cwd) {
    run("corepack", ["pnpm", ...args], cwd);
}

function firstExisting(...dirs) {
    return dirs.find((dir) => dir && existsSync(dir));
}

function copyDir(from, to, filter) {
    rmSync(to, { recursive: true, force: true });
    cpSync(from, to, { recursive: true, dereference: true, filter });
}

function stageBackend() {
    const from = firstExisting(arg("--backend"), join(INPUTS, "backend"), join(REPO, "bundles", "backend"), join(REPO, "backend", "target", "dist"));
    if (!from || !existsSync(join(from, "penpot.jar"))) {
        throw new Error("no backend build: pass --backend <dir with penpot.jar>");
    }
    const to = join(RUNTIME, "backend");
    rmSync(to, { recursive: true, force: true });
    mkdirSync(to, { recursive: true });
    for (const name of ["penpot.jar", "log4j2.xml", "builtin-templates", "version.txt"]) {
        if (existsSync(join(from, name))) {
            cpSync(join(from, name), join(to, name), { recursive: true });
        }
    }
    console.log(`backend from ${from}`);
}

function stageFrontend() {
    const from = firstExisting(arg("--frontend"), join(INPUTS, "frontend"), join(REPO, "bundles", "frontend"), join(REPO, "frontend", "target", "dist"));
    if (!from || !existsSync(join(from, "index.html"))) {
        throw new Error("no frontend build: pass --frontend <dir with index.html>");
    }
    // config.js is generated by the gateway at run time
    copyDir(from, join(RUNTIME, "frontend"), (src) => !src.endsWith(join("js", "config.js")));
    const plugin = firstExisting(join(from, "plugins", "mcp", "manifest.json") && join(from, "plugins", "mcp"), join(REPO, "mcp", "packages", "plugin", "dist"));
    if (plugin && existsSync(join(plugin, "manifest.json"))) {
        copyDir(plugin, join(RUNTIME, "mcp-plugin"));
    } else {
        console.warn("warning: no MCP plugin build found (AI canvas tools will not load)");
    }
    console.log(`frontend from ${from}`);
}

/** Keeps only the ripgrep binary of this platform in the Claude Agent SDK (saves ~50 MB). */
function pruneAgentSdk(nodeModules) {
    const vendor = join(nodeModules, "@anthropic-ai", "claude-agent-sdk", "vendor", "ripgrep");
    if (!existsSync(vendor)) {
        return;
    }
    const keep = `${process.arch}-${process.platform}`;
    for (const entry of readdirSync(vendor)) {
        if (entry.includes("-") && entry !== keep) {
            rmSync(join(vendor, entry), { recursive: true, force: true });
        }
    }
}

function stageDaemon(skipBuild) {
    const mcp = join(REPO, "mcp");
    if (!skipBuild) {
        pnpm(["install", "--frozen-lockfile"], mcp);
        pnpm(["--filter", "mcp-common", "--filter", "mcp-server", "--filter", "mcp-plugin", "run", "build"], mcp);
    }
    const to = join(RUNTIME, "daemon");
    rmSync(to, { recursive: true, force: true });
    // a flat node_modules without symlinks: installers copy files, not links
    pnpm(["--filter", "mcp-server", "deploy", "--prod", "--legacy", "--config.node-linker=hoisted", to], mcp);
    for (const dir of ["src", "scripts", "test", "tsconfig.json"]) {
        rmSync(join(to, dir), { recursive: true, force: true });
    }
    pruneAgentSdk(join(to, "node_modules"));
    if (!existsSync(join(to, "dist", "index.js"))) {
        throw new Error("daemon build missing dist/index.js");
    }
    if (!existsSync(join(RUNTIME, "mcp-plugin")) && existsSync(join(mcp, "packages", "plugin", "dist", "manifest.json"))) {
        copyDir(join(mcp, "packages", "plugin", "dist"), join(RUNTIME, "mcp-plugin"));
    }
}

function stageMediaProcessor(skipBuild) {
    const src = join(REPO, "media-processor");
    if (!skipBuild) {
        pnpm(["install", "--frozen-lockfile"], src);
        pnpm(["run", "build"], src);
    }
    const to = join(RUNTIME, "media-processor");
    rmSync(to, { recursive: true, force: true });
    mkdirSync(to, { recursive: true });
    cpSync(join(src, "dist"), join(to, "dist"), { recursive: true });
    cpSync(join(src, "pnpm-lock.yaml"), join(to, "pnpm-lock.yaml"));
    const pkg = JSON.parse(readFileSync(join(src, "package.json"), "utf8"));
    delete pkg.devDependencies;
    delete pkg.scripts;
    writeFileSync(join(to, "package.json"), JSON.stringify(pkg, null, 2));
    writeFileSync(join(to, "pnpm-workspace.yaml"), `storeDir: ${JSON.stringify(join(REPO, ".pnpm-store"))}\nallowBuilds:\n  sharp: false\n`);
    pnpm(["install", "--prod", "--frozen-lockfile", "--config.node-linker=hoisted"], to);
    rmSync(join(to, "pnpm-workspace.yaml"), { force: true });
}

function writeVersion() {
    const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
    const commit = spawnSync("git", ["rev-parse", "--short=12", "HEAD"], { cwd: REPO, encoding: "utf8" }).stdout.trim();
    const backendVersion = existsSync(join(RUNTIME, "backend", "version.txt")) ? readFileSync(join(RUNTIME, "backend", "version.txt"), "utf8").trim() : undefined;
    writeFileSync(join(RUNTIME, "version.json"), JSON.stringify({ desktop: pkg.version, commit, backend: backendVersion }, null, 2));
}

function collectLicenses() {
    const out = join(RUNTIME, "licenses");
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    const sources = [
        ["penpot-MPL-2.0.txt", join(REPO, "LICENSE")],
        ["jre", join(RUNTIME, "jre", "legal")],
        ["postgresql-COPYRIGHT.txt", join(RUNTIME, "postgres", "share", "COPYRIGHT")],
        ["sharp-LICENSE.txt", join(RUNTIME, "media-processor", "node_modules", "sharp", "LICENSE")],
        ["claude-agent-sdk-LICENSE.md", join(RUNTIME, "daemon", "node_modules", "@anthropic-ai", "claude-agent-sdk", "LICENSE.md")],
    ];
    for (const [name, from] of sources) {
        if (existsSync(from)) {
            cpSync(from, join(out, name), { recursive: true });
        }
    }
    const libvips = firstExisting(
        ...["media-processor", "daemon"].flatMap((part) => {
            const img = join(RUNTIME, part, "node_modules", "@img");
            return existsSync(img) ? readdirSync(img).filter((e) => e.startsWith("sharp-libvips")).map((e) => join(img, e)) : [];
        }),
    );
    if (libvips) {
        for (const file of readdirSync(libvips).filter((f) => /license|thirdparty|versions/i.test(f))) {
            cpSync(join(libvips, file), join(out, `libvips-${file}`), { recursive: true });
        }
    }
}

const skipNode = process.argv.includes("--skip-node-builds");
mkdirSync(RUNTIME, { recursive: true });
stageBackend();
stageFrontend();
stageDaemon(skipNode);
stageMediaProcessor(skipNode);
writeVersion();
collectLicenses();
console.log(`runtime staged in ${RUNTIME}`);
