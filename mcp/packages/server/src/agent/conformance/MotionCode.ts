import { MotionEasing, type MotionEasingValue } from "./MotionEasing";
import { type LayerMotion, type MotionClip, type MotionState, type MotionTrack } from "./MotionModel";

/** Animation library of an app stack. */
export type MotionLibraryId = "framer-motion" | "css" | "reanimated";

/** Animated layer with the name its motion has in the code. */
export interface NamedMotion {
    /** identifier (`loginSignInButton`) or, in CSS, the class name without `pf-` */
    key: string;
    /** where it is in the design, for the comment */
    label: string;
    motion: LayerMotion;
}

/**
 * Generator of the app's motion file: every animation of the design as code values, so the app
 * runs them with the same durations, delays, easings, springs and stagger. Output is text only
 * (no imports), in one of three forms: props for Framer Motion, plain data for Reanimated, CSS
 * keyframes and classes.
 */
export abstract class MotionCode {
    protected static readonly HEADER =
        "Generated by Penforge from the animations of the Penpot design. Do not edit: change the " +
        "animation in Penpot; every build writes this file again.";

    /**
     * Gets the generator of a library.
     *
     * @param library - animation library of the stack
     * @param typescript - whether the app is TypeScript (not used by CSS)
     */
    public static of(library: MotionLibraryId, typescript: boolean): MotionCode {
        switch (library) {
            case "framer-motion":
                return new FramerMotionCode(typescript);
            case "reanimated":
                return new ReanimatedCode(typescript);
            default:
                return new CssMotionCode();
        }
    }

    /** Extension of the file, with the dot. */
    public abstract readonly extension: string;

    /**
     * Generates the file.
     *
     * @param motions - animated layers in design order
     */
    public abstract file(motions: NamedMotion[]): string;

    /**
     * Gets how the code of a layer names its motion, for prompts (`loginCard.enter`, `pf-login-card-enter`).
     *
     * @param named - the animated layer
     */
    public abstract references(named: NamedMotion): string[];

    /** Pattern that finds any use of a layer's motion in the app's code. */
    public abstract usage(key: string): RegExp;

    /** Text that is safe inside a block comment. */
    protected static comment(text: string): string {
        return text.replace(/\*\//g, "* /").replace(/\s+/g, " ").trim().slice(0, 200);
    }

    protected static round(value: number): number {
        return Math.round(value * 10000) / 10000;
    }

    /** `rgba(…)` of a `#rrggbb` color. */
    protected static rgba(hex: string, opacity: number): string {
        const channel = (i: number) => parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) || 0;
        return `rgba(${channel(0)}, ${channel(1)}, ${channel(2)}, ${MotionCode.round(opacity)})`;
    }

    /** Names of the sections a motion has. */
    protected static sections(motion: LayerMotion): string[] {
        return [
            ...(motion.enter ? ["enter"] : []),
            ...(motion.exit ? ["exit"] : []),
            ...(motion.hover ? ["hover"] : []),
            ...(motion.press ? ["press"] : []),
            ...(motion.loop ? ["loop"] : []),
        ];
    }

    /** PascalCase identifier part of a name. */
    public static pascal(name: string): string {
        return name
            .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
            .split(/[^A-Za-z0-9]+/)
            .filter((word) => word.length > 0)
            .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
            .join("");
    }

    /** kebab-case of an identifier. */
    public static kebab(key: string): string {
        return key
            .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
            .replace(/[^A-Za-z0-9]+/g, "-")
            .toLowerCase();
    }
}

/** Object literal writer shared by the JavaScript forms. */
abstract class ScriptMotionCode extends MotionCode {
    public readonly extension: string;

    constructor(protected readonly typescript: boolean) {
        super();
        this.extension = typescript ? ".ts" : ".js";
    }

    public references(named: NamedMotion): string[] {
        const names = MotionCode.sections(named.motion).map((section) => `${named.key}.${section}`);
        return named.motion.smart.length > 0 ? [...names, `${named.key}.smart`] : names;
    }

    public usage(key: string): RegExp {
        return new RegExp(`\\b${key}\\b`);
    }

    /** Four bezier points, typed as a tuple in TypeScript. */
    protected bezier(points: number[]): string {
        const text = `[${points.join(", ")}]`;
        return this.typescript ? `${text} as [number, number, number, number]` : text;
    }

    protected literal(text: string): string {
        return this.typescript ? `"${text}" as const` : `"${text}"`;
    }

    protected static value(value: number | string): string {
        return typeof value === "number" ? String(MotionCode.round(value)) : JSON.stringify(value);
    }

    /** Extra parameters of a staggered motion. */
    protected parameters(): string {
        return this.typescript ? "(index: number, count: number)" : "(index, count)";
    }

    /** Helper that computes a staggered child's extra delay, in the unit of `each`. */
    protected staggerHelper(): string {
        const typed = this.typescript
            ? '(index: number, count: number, each: number, from: "first" | "last" | "center")'
            : "(index, count, each, from)";
        return [
            "/* Extra delay of child `index` of `count` (reading order) in a stagger. */",
            `export function staggerDelay${typed} {`,
            '    if (from === "last") {',
            "        return (count - 1 - index) * each;",
            "    }",
            '    return (from === "center" ? Math.floor(Math.abs(index - (count - 1) / 2)) : index) * each;',
            "}",
        ].join("\n");
    }
}

/** Framer Motion: `initial` / `animate` / `exit` / `whileHover` / `whileTap` props. */
class FramerMotionCode extends ScriptMotionCode {
    private static readonly PROPS: Record<string, string> = {
        opacity: "opacity",
        translateX: "x",
        translateY: "y",
        scale: "scale",
        rotate: "rotate",
        blur: "filter",
        fill: "backgroundColor",
        shimmer: "x",
    };

    public file(motions: NamedMotion[]): string {
        const staggered = motions.some((m) => m.motion.enter?.stagger || m.motion.exit?.stagger);
        const parts = [
            `/* ${MotionCode.HEADER}\n` +
                " * Framer Motion props: spread `enter` and `exit` on the motion element (exit needs AnimatePresence),\n" +
                " * `hover` and `press` too; `loop` goes on its own element inside. Staggered motions are functions of\n" +
                " * the child's index and the number of children. */",
        ];
        if (staggered) {
            parts.push(this.staggerHelper());
        }
        for (const named of motions) {
            const lines = [`/* ${MotionCode.comment(named.label)} */`, `export const ${named.key} = {`];
            const { enter, exit, hover, press, loop, smart } = named.motion;
            if (enter) {
                lines.push(`    enter: ${this.staggerable(enter, (delay) => this.enter(enter, delay))},`);
            }
            if (exit) {
                lines.push(`    exit: ${this.staggerable(exit, (delay) => this.exit(exit, delay))},`);
            }
            if (hover) {
                lines.push(`    hover: { whileHover: ${this.state(hover)} },`);
            }
            if (press) {
                lines.push(`    press: { whileTap: ${this.state(press)} },`);
            }
            if (loop) {
                lines.push(`    loop: ${this.loop(loop)},`);
            }
            if (smart.length > 0) {
                const entries = smart.map(
                    (link) =>
                        `to${MotionCode.pascal(link.destinationName) || "Screen"}: { transition: ${this.transition(link.duration, "0", [link.easing])} }`
                );
                lines.push(`    smart: { ${entries.join(", ")} },`);
            }
            lines.push("};");
            parts.push(lines.join("\n"));
        }
        if (motions.length === 0) {
            parts.push("export {};");
        }
        return parts.join("\n\n") + "\n";
    }

    private staggerable(clip: MotionClip, body: (delay: string) => string): string {
        const base = MotionCode.round(clip.delay / 1000);
        if (clip.stagger === null) {
            return body(String(base));
        }
        const { each, from } = clip.stagger;
        const extra = `staggerDelay(index, count, ${MotionCode.round(each / 1000)}, "${from}")`;
        return `${this.parameters()} => (${body(`${base} + ${extra}`)})`;
    }

    private enter(clip: MotionClip, delay: string): string {
        const initial = clip.tracks.map(
            (track) => `${this.prop(track)}: ${FramerMotionCode.frame(track, track.values[0])}`
        );
        return `{ initial: { ${initial.join(", ")} }, animate: ${this.target(clip, delay)} }`;
    }

    private exit(clip: MotionClip, delay: string): string {
        return `{ exit: ${this.target(clip, delay)} }`;
    }

    private loop(clip: MotionClip): string {
        const delay = String(MotionCode.round(clip.delay / 1000));
        const repeat = clip.iterations === "infinite" ? "Infinity" : String(Math.max(0, clip.iterations - 1));
        if (clip.tracks.some((track) => track.prop === "shimmer")) {
            const transition = this.transition(clip.duration, delay, clip.tracks[0].easings, `repeat: ${repeat}`);
            const style =
                'position: "absolute", top: 0, bottom: 0, left: 0, width: "50%", pointerEvents: "none", ' +
                'background: "linear-gradient(90deg, rgba(255, 255, 255, 0), rgba(255, 255, 255, 0.6), rgba(255, 255, 255, 0))"';
            const typedStyle = this.typescript
                ? `{ ${style.replace('"absolute"', '"absolute" as const').replace('"none"', '"none" as const')} }`
                : `{ ${style} }`;
            return (
                `{ overlay: { "aria-hidden": true, style: ${typedStyle}, ` +
                `animate: { x: ["-100%", "200%"], transition: ${transition} } } }`
            );
        }
        return `{ animate: ${this.target(clip, delay, `repeat: ${repeat}`)} }`;
    }

    /** Target of `animate`/`exit`/loops: end values (or all keyframes) and the transition. */
    private target(clip: MotionClip, delay: string, extra = ""): string {
        const values = clip.tracks.map((track) => {
            const simple = track.values.length === 2 && extra.length === 0;
            const value = simple
                ? FramerMotionCode.frame(track, track.values[1])
                : `[${track.values.map((v) => FramerMotionCode.frame(track, v)).join(", ")}]`;
            return `${this.prop(track)}: ${value}`;
        });
        const transitions = clip.tracks.map((track) => this.trackTransition(clip, track, delay, extra));
        const same = transitions.every((transition) => transition === transitions[0]);
        const transition = same
            ? (transitions[0] ?? this.transition(clip.duration, delay, [MotionEasing.parse("linear", "linear")], extra))
            : `{ ${clip.tracks.map((track, i) => `${this.prop(track)}: ${transitions[i]}`).join(", ")} }`;
        return `{ ${[...values, `transition: ${transition}`].join(", ")} }`;
    }

    private trackTransition(clip: MotionClip, track: MotionTrack, delay: string, extra: string): string {
        const times = track.values.length > 2 ? `times: [${track.times.map(MotionCode.round).join(", ")}]` : "";
        return this.transition(clip.duration, delay, track.easings, [times, extra].filter(Boolean).join(", "));
    }

    private transition(durationMs: number, delay: string, easings: MotionEasingValue[], extra = ""): string {
        const first = easings[0];
        const parts: string[] = [];
        if (easings.length === 1 && first.kind === "spring") {
            parts.push(
                `type: ${this.literal("spring")}`,
                `stiffness: ${first.stiffness}`,
                `damping: ${first.damping}`,
                `mass: ${first.mass}`
            );
        } else {
            parts.push(`duration: ${MotionCode.round(durationMs / 1000)}`);
            const linear = easings.every((easing) => MotionEasing.isLinear(easing));
            if (linear) {
                parts.push(`ease: ${this.literal("linear")}`);
            } else if (easings.length === 1) {
                parts.push(`ease: ${this.bezier((first as { points: number[] }).points)}`);
            } else {
                const list = easings.map((easing) => `[${(easing as { points: number[] }).points.join(", ")}]`);
                const text = `[${list.join(", ")}]`;
                parts.push(`ease: ${this.typescript ? `${text} as [number, number, number, number][]` : text}`);
            }
        }
        if (delay !== "0") {
            parts.push(`delay: ${delay}`);
        }
        if (extra.length > 0) {
            parts.push(extra);
        }
        return `{ ${parts.join(", ")} }`;
    }

    private state(state: MotionState): string {
        const { opacity, scale, translateX, translateY, fill, shadow } = state.values;
        const values = [
            ...(opacity !== undefined ? [`opacity: ${opacity}`] : []),
            ...(scale !== undefined ? [`scale: ${scale}`] : []),
            ...(translateX !== undefined ? [`x: ${translateX}`] : []),
            ...(translateY !== undefined ? [`y: ${translateY}`] : []),
            ...(fill !== undefined ? [`backgroundColor: "${fill}"`] : []),
            ...(shadow !== undefined
                ? [
                      `boxShadow: "${shadow.x}px ${shadow.y}px ${shadow.blur}px ${shadow.spread}px ${MotionCode.rgba(shadow.color, shadow.opacity)}"`,
                  ]
                : []),
        ];
        return `{ ${[...values, `transition: ${this.transition(state.duration, "0", [state.easing])}`].join(", ")} }`;
    }

    private prop(track: MotionTrack): string {
        return FramerMotionCode.PROPS[track.prop];
    }

    private static frame(track: MotionTrack, value: number | string): string {
        return track.prop === "blur" ? `"blur(${value}px)"` : ScriptMotionCode.value(value);
    }
}

/** Reanimated: plain data read by `withTiming` / `withSpring` / `withRepeat`. */
class ReanimatedCode extends ScriptMotionCode {
    public file(motions: NamedMotion[]): string {
        const staggered = motions.some((m) => m.motion.enter?.stagger || m.motion.exit?.stagger);
        const parts = [
            `/* ${MotionCode.HEADER}\n` +
                " * Values for Reanimated, times in ms: `bezier` goes to Easing.bezier(...bezier) in withTiming, `spring`\n" +
                " * to withSpring; `repeat` -1 is endless (withRepeat). Tracks run together; a track with more than two\n" +
                " * values is a withSequence over `times`. */",
        ];
        if (staggered) {
            parts.push(this.staggerHelper());
        }
        for (const named of motions) {
            const { enter, exit, hover, press, loop, smart } = named.motion;
            const lines = [`/* ${MotionCode.comment(named.label)} */`, `export const ${named.key} = {`];
            for (const [name, clip] of [
                ["enter", enter],
                ["exit", exit],
                ["loop", loop],
            ] as const) {
                if (clip) {
                    lines.push(`    ${name}: ${this.clip(clip)},`);
                }
            }
            for (const [name, state] of [
                ["hover", hover],
                ["press", press],
            ] as const) {
                if (state) {
                    const values = Object.entries(state.values).map(
                        ([key, value]) =>
                            `${key}: ${typeof value === "object" ? JSON.stringify(value) : ScriptMotionCode.value(value as number | string)}`
                    );
                    lines.push(
                        `    ${name}: { to: { ${values.join(", ")} }, duration: ${state.duration}, ${this.easing(state.easing)} },`
                    );
                }
            }
            if (smart.length > 0) {
                const entries = smart.map(
                    (link) =>
                        `to${MotionCode.pascal(link.destinationName) || "Screen"}: { duration: ${link.duration}, ${this.easing(link.easing)} }`
                );
                lines.push(`    smart: { ${entries.join(", ")} },`);
            }
            lines.push("};");
            parts.push(lines.join("\n"));
        }
        if (motions.length === 0) {
            parts.push("export {};");
        }
        return parts.join("\n\n") + "\n";
    }

    private clip(clip: MotionClip): string {
        const tracks = clip.tracks.map((track) => {
            const values = `values: [${track.values.map((value) => ScriptMotionCode.value(value)).join(", ")}]`;
            const times = track.values.length > 2 ? `, times: [${track.times.map(MotionCode.round).join(", ")}]` : "";
            const first = track.easings[0];
            const easing =
                track.easings.length === 1
                    ? `, ${this.easing(first)}`
                    : track.sampled
                      ? ", linear: true"
                      : `, easings: [${track.easings.map((e) => this.bezier((e as { points: number[] }).points)).join(", ")}]`;
            return `${track.prop}: { ${values}${times}${easing} }`;
        });
        const repeat =
            clip.iterations === "infinite" ? ", repeat: -1" : clip.iterations > 1 ? `, repeat: ${clip.iterations}` : "";
        const stagger = clip.stagger
            ? `, stagger: { each: ${clip.stagger.each}, from: ${this.literal(clip.stagger.from)} }`
            : "";
        return `{ duration: ${clip.duration}, delay: ${clip.delay}${repeat}${stagger}, tracks: { ${tracks.join(", ")} } }`;
    }

    private easing(easing: MotionEasingValue): string {
        return easing.kind === "spring"
            ? `spring: { stiffness: ${easing.stiffness}, damping: ${easing.damping}, mass: ${easing.mass} }`
            : `bezier: ${this.bezier(easing.points)}`;
    }
}

/** CSS: keyframes plus one class per section (`pf-<layer>-enter`, `-exit`, `-states`, `-loop`). */
class CssMotionCode extends MotionCode {
    public readonly extension = ".css";

    public file(motions: NamedMotion[]): string {
        const parts = [
            `/* ${MotionCode.HEADER}\n` +
                " * Put the class on the element of the layer. Staggered motions: put the class on the parent and set\n" +
                " * --pf-i (index, 0-based) and --pf-n (number of children) on each child. Exit: add the class, remove\n" +
                " * the element on animationend. A loop next to an entrance goes on its own element inside. */",
        ];
        for (const named of motions) {
            const name = `pf-${MotionCode.kebab(named.key)}`;
            const { enter, exit, hover, press, loop, smart } = named.motion;
            parts.push(`/* ${MotionCode.comment(named.label)} */`);
            if (enter) {
                parts.push(this.clip(`${name}-enter`, enter, "both"));
            }
            if (exit) {
                parts.push(this.clip(`${name}-exit`, exit, "both"));
            }
            if (hover || press) {
                parts.push(this.states(name, hover, press));
            }
            if (loop) {
                parts.push(this.clip(`${name}-loop`, loop, "none"));
            }
            for (const link of smart) {
                const target = MotionCode.kebab(MotionCode.pascal(link.destinationName) || "screen");
                parts.push(
                    `.${name}-smart-${target} { transition: all ${link.duration}ms ${this.timing(link.easing)}; ` +
                        `view-transition-name: ${name}; }\n` +
                        `::view-transition-group(${name}) { animation-duration: ${link.duration}ms; ` +
                        `animation-timing-function: ${this.timing(link.easing)}; }`
                );
            }
        }
        return parts.join("\n\n") + "\n";
    }

    public references(named: NamedMotion): string[] {
        const name = `pf-${MotionCode.kebab(named.key)}`;
        const { enter, exit, hover, press, loop, smart } = named.motion;
        return [
            ...(enter ? [`.${name}-enter`] : []),
            ...(exit ? [`.${name}-exit`] : []),
            ...(hover || press ? [`.${name}-states`] : []),
            ...(loop ? [`.${name}-loop`] : []),
            ...smart.map(
                (link) => `.${name}-smart-${MotionCode.kebab(MotionCode.pascal(link.destinationName) || "screen")}`
            ),
        ];
    }

    public usage(key: string): RegExp {
        return new RegExp(`\\bpf-${MotionCode.kebab(key)}-(?:enter|exit|states|loop|smart)`);
    }

    private clip(name: string, clip: MotionClip, fill: "both" | "none"): string {
        const keyframes: string[] = [];
        const animations: string[] = [];
        const iterations =
            clip.iterations === "infinite" ? " infinite" : clip.iterations > 1 ? ` ${clip.iterations}` : "";
        for (const group of CssMotionCode.groups(clip.tracks)) {
            const id =
                group.length === 1 && clip.tracks.length === 1 ? name : `${name}-${CssMotionCode.groupName(group)}`;
            keyframes.push(this.keyframes(id, group));
            const single = group[0].easings.length === 1 ? group[0].easings[0] : MotionEasing.parse("linear", "linear");
            animations.push(`${id} ${clip.duration}ms ${this.timing(single)} ${clip.delay}ms${iterations} ${fill}`);
        }
        if (clip.tracks.some((track) => track.prop === "shimmer")) {
            return [
                ...keyframes,
                `.${name} { position: relative; overflow: hidden; }`,
                `.${name}::after { content: ""; position: absolute; top: 0; bottom: 0; left: 0; width: 50%; pointer-events: none; ` +
                    "background: linear-gradient(90deg, rgba(255, 255, 255, 0), rgba(255, 255, 255, 0.6), rgba(255, 255, 255, 0)); " +
                    `animation: ${animations.join(", ")}; }`,
            ].join("\n");
        }
        if (clip.stagger === null) {
            return [...keyframes, `.${name} { animation: ${animations.join(", ")}; }`].join("\n");
        }
        const { each, from } = clip.stagger;
        const index =
            from === "last"
                ? "(var(--pf-n, 1) - 1 - var(--pf-i, 0))"
                : from === "center"
                  ? "round(down, abs(var(--pf-i, 0) - (var(--pf-n, 1) - 1) / 2), 1)"
                  : "var(--pf-i, 0)";
        const delays = animations.map(() => `calc(${clip.delay}ms + ${index} * ${each}ms)`);
        return [
            ...keyframes,
            `.${name} > * { animation: ${animations.join(", ")}; animation-delay: ${delays.join(", ")}; }`,
        ].join("\n");
    }

    /** Tracks in groups of one CSS property each (`translateX` and `translateY` share `translate`). */
    private static groups(tracks: MotionTrack[]): MotionTrack[][] {
        const x = tracks.find((track) => track.prop === "translateX");
        const y = tracks.find((track) => track.prop === "translateY");
        const rest = tracks.filter((track) => track !== x && track !== y).map((track) => [track]);
        const moves = [x, y].filter((track): track is MotionTrack => track !== undefined);
        return [...rest, ...(moves.length > 0 ? [moves] : [])];
    }

    private static groupName(group: MotionTrack[]): string {
        return group[0].prop.startsWith("translate") ? "move" : group[0].prop;
    }

    private keyframes(id: string, group: MotionTrack[]): string {
        const [first, second] = group;
        const times = second ? [...new Set([...first.times, ...second.times])].sort((a, b) => a - b) : first.times;
        const lines = times.map((time, i) => {
            const declarations =
                second !== undefined
                    ? [`translate: ${CssMotionCode.at(first, time)}px ${CssMotionCode.at(second, time)}px`]
                    : [CssMotionCode.declaration(first, first.values[i])];
            // the easing of a keyframe is the one of the segment that starts there
            const easing = first.easings.length > 1 && !first.sampled ? first.easings[i] : undefined;
            if (easing !== undefined) {
                declarations.push(`animation-timing-function: ${this.timing(easing)}`);
            }
            return `    ${MotionCode.round(time * 100)}% { ${declarations.join("; ")}; }`;
        });
        return `@keyframes ${id} {\n${lines.join("\n")}\n}`;
    }

    /** Value of a track at a time, interpolated between its points. */
    private static at(track: MotionTrack, time: number): number {
        let i = 0;
        while (i < track.times.length - 2 && time > track.times[i + 1]) {
            i++;
        }
        const span = track.times[i + 1] - track.times[i];
        const local = span > 0 ? (time - track.times[i]) / span : 1;
        const from = Number(track.values[i]);
        return MotionCode.round(from + (Number(track.values[i + 1]) - from) * local);
    }

    private static declaration(track: MotionTrack, value: number | string): string {
        switch (track.prop) {
            case "opacity":
                return `opacity: ${value}`;
            case "translateX":
                return `translate: ${value}px 0`;
            case "translateY":
                return `translate: 0 ${value}px`;
            case "scale":
                return `scale: ${value}`;
            case "rotate":
                return `rotate: ${value}deg`;
            case "blur":
                return `filter: blur(${value}px)`;
            case "fill":
                return `background-color: ${value}`;
            case "shimmer":
                return `transform: translateX(${MotionCode.round(-100 + 300 * Number(value))}%)`;
        }
    }

    private states(name: string, hover: MotionState | null, press: MotionState | null): string {
        const rest = (hover ?? press)!;
        const rules = [
            `.${name}-states { transition: opacity, scale, translate, background-color, box-shadow; ` +
                `transition-duration: ${rest.duration}ms; transition-timing-function: ${this.timing(rest.easing)}; }`,
        ];
        for (const [selector, state] of [
            [":hover", hover],
            [":active", press],
        ] as const) {
            if (state) {
                rules.push(
                    `.${name}-states${selector} { ${CssMotionCode.stateDeclarations(state).join("; ")}; ` +
                        `transition-duration: ${state.duration}ms; transition-timing-function: ${this.timing(state.easing)}; }`
                );
            }
        }
        return rules.join("\n");
    }

    private static stateDeclarations(state: MotionState): string[] {
        const { opacity, scale, translateX, translateY, fill, shadow } = state.values;
        return [
            ...(opacity !== undefined ? [`opacity: ${opacity}`] : []),
            ...(scale !== undefined ? [`scale: ${scale}`] : []),
            ...(translateX !== undefined || translateY !== undefined
                ? [`translate: ${translateX ?? 0}px ${translateY ?? 0}px`]
                : []),
            ...(fill !== undefined ? [`background-color: ${fill}`] : []),
            ...(shadow !== undefined
                ? [
                      `box-shadow: ${shadow.x}px ${shadow.y}px ${shadow.blur}px ${shadow.spread}px ${MotionCode.rgba(shadow.color, shadow.opacity)}`,
                  ]
                : []),
        ];
    }

    /** Timing function; a spring becomes a `linear()` curve over its settle time. */
    private timing(easing: MotionEasingValue): string {
        if (easing.kind === "spring") {
            const points = Array.from({ length: 41 }, (_, i) => MotionCode.round(MotionEasing.at(easing, i / 40)));
            return `linear(${points.join(", ")})`;
        }
        return MotionEasing.isLinear(easing) ? "linear" : `cubic-bezier(${easing.points.join(", ")})`;
    }
}
